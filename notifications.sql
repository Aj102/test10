-- =========================================================
-- Notifications: portfolio ratings, featured-slot ratings,
-- and project views.
-- Run this in the Supabase SQL Editor (safe to run more than once).
-- =========================================================

-- 1) Notification inbox -------------------------------------------------
create table if not exists public.notifications (
    id             bigint generated by default as identity primary key,
    user_id        uuid not null references auth.users(id) on delete cascade,
    actor_id       uuid references auth.users(id) on delete set null,
    type           text not null,
    project_id     bigint references public.projects(id) on delete set null,
    project_title  text,
    featured_slot  integer,
    score          integer,
    actor_name     text,
    actor_strand   text,
    actor_grade    text,
    actor_section  text,
    is_read        boolean not null default false,
    created_at     timestamptz not null default now()
);

create index if not exists notifications_user_created_idx
    on public.notifications (user_id, created_at desc);

create index if not exists notifications_user_unread_idx
    on public.notifications (user_id, is_read);

create index if not exists notifications_view_dedupe_idx
    on public.notifications (user_id, project_id, actor_id, created_at desc)
    where type = 'project_view';

-- 2) Raw project view events -------------------------------------------
create table if not exists public.project_views (
    id          bigint generated by default as identity primary key,
    project_id  bigint not null references public.projects(id) on delete cascade,
    viewer_id   uuid references auth.users(id) on delete set null,
    created_at  timestamptz not null default now()
);

create index if not exists project_views_project_idx
    on public.project_views (project_id, created_at desc);

-- 3) Notify the portfolio owner when their student rating changes -------
create or replace function public.notify_portfolio_rating()
returns trigger
language plpgsql
security definer
set search_path = public, pg_temp
as $$
declare
    v_actor public.profiles%rowtype;
    v_name  text;
begin
    if tg_op = 'UPDATE' then
        if new.score is not distinct from old.score then
            return new;
        end if;
    end if;
    if new.author_id is null or new.author_id = new.rater_id then
        return new;
    end if;

    select * into v_actor from public.profiles where id = new.rater_id;
    v_name := nullif(trim(coalesce(v_actor.fname, '') || ' ' || coalesce(v_actor.lname, '')), '');

    insert into public.notifications (
        user_id, actor_id, type, score,
        actor_name, actor_strand, actor_grade, actor_section
    ) values (
        new.author_id,
        new.rater_id,
        'portfolio_rating',
        round(new.score)::int,
        coalesce(v_name, 'A student'),
        v_actor.strand,
        v_actor.grade,
        v_actor.section
    );

    return new;
end;
$$;

drop trigger if exists trg_notify_portfolio_rating on public.ratings;
create trigger trg_notify_portfolio_rating
    after insert or update of score on public.ratings
    for each row execute function public.notify_portfolio_rating();

-- 4) Notify the owner when a featured project slot is rated -------------
create or replace function public.notify_featured_rating()
returns trigger
language plpgsql
security definer
set search_path = public, pg_temp
as $$
declare
    v_actor   public.profiles%rowtype;
    v_name    text;
    v_caption text;
begin
    if tg_op = 'UPDATE' then
        if new.score is not distinct from old.score then
            return new;
        end if;
    end if;
    if new.owner_id is null or new.owner_id = new.rater_id then
        return new;
    end if;

    select caption into v_caption
    from public.featured
    where user_id = new.owner_id and slot = new.slot
    limit 1;

    select * into v_actor from public.profiles where id = new.rater_id;
    v_name := nullif(trim(coalesce(v_actor.fname, '') || ' ' || coalesce(v_actor.lname, '')), '');

    insert into public.notifications (
        user_id, actor_id, type, featured_slot, score, project_title,
        actor_name, actor_strand, actor_grade, actor_section
    ) values (
        new.owner_id,
        new.rater_id,
        'featured_rating',
        new.slot,
        round(new.score)::int,
        v_caption,
        coalesce(v_name, 'A student'),
        v_actor.strand,
        v_actor.grade,
        v_actor.section
    );

    return new;
end;
$$;

drop trigger if exists trg_notify_featured_rating on public.featured_ratings;
create trigger trg_notify_featured_rating
    after insert or update of score on public.featured_ratings
    for each row execute function public.notify_featured_rating();

-- 5) Notify the owner when a public project is viewed -------------------
-- Guests are allowed (viewer_id is null). Repeat views by the same
-- visitor for the same project are collapsed into one notification
-- per 12 hours so the inbox does not get spammed.
create or replace function public.notify_project_view()
returns trigger
language plpgsql
security definer
set search_path = public, pg_temp
as $$
declare
    v_project public.projects%rowtype;
    v_actor   public.profiles%rowtype;
    v_name    text;
begin
    select * into v_project from public.projects where id = new.project_id;
    if v_project.id is null or v_project.user_id is null then
        return new;
    end if;
    if new.viewer_id = v_project.user_id then
        return new;
    end if;

    if exists (
        select 1
        from public.notifications n
        where n.user_id = v_project.user_id
          and n.type = 'project_view'
          and n.project_id = new.project_id
          and n.actor_id is not distinct from new.viewer_id
          and n.created_at > now() - interval '12 hours'
    ) then
        return new;
    end if;

    if new.viewer_id is not null then
        select * into v_actor from public.profiles where id = new.viewer_id;
        v_name := nullif(trim(coalesce(v_actor.fname, '') || ' ' || coalesce(v_actor.lname, '')), '');
    end if;

    insert into public.notifications (
        user_id, actor_id, type, project_id, project_title,
        actor_name, actor_strand, actor_grade, actor_section
    ) values (
        v_project.user_id,
        new.viewer_id,
        'project_view',
        new.project_id,
        v_project.title,
        coalesce(v_name, case when new.viewer_id is null then 'Guest visitor' else 'A student' end),
        v_actor.strand,
        v_actor.grade,
        v_actor.section
    );

    return new;
end;
$$;

drop trigger if exists trg_notify_project_view on public.project_views;
create trigger trg_notify_project_view
    after insert on public.project_views
    for each row execute function public.notify_project_view();

-- 6) Row Level Security -------------------------------------------------
alter table public.notifications enable row level security;
alter table public.project_views enable row level security;

drop policy if exists "notifications_select_own" on public.notifications;
create policy "notifications_select_own"
    on public.notifications for select
    to authenticated
    using (user_id = auth.uid());

drop policy if exists "notifications_update_own" on public.notifications;
create policy "notifications_update_own"
    on public.notifications for update
    to authenticated
    using (user_id = auth.uid())
    with check (user_id = auth.uid());

-- Anyone (including a logged-out QR visitor) may log a view, but the
-- viewer id must be their own account when one is supplied.
drop policy if exists "project_views_insert_public" on public.project_views;
create policy "project_views_insert_public"
    on public.project_views for insert
    to anon, authenticated
    with check (viewer_id is null or viewer_id = auth.uid());

grant select, update on public.notifications to authenticated;
grant insert on public.project_views to anon, authenticated;
grant usage, select on sequence public.project_views_id_seq to anon, authenticated;
grant usage, select on sequence public.notifications_id_seq to authenticated;

-- 7) Quick check -------------------------------------------------------
select
    (select count(*) from public.notifications) as notification_rows,
    (select count(*) from public.project_views) as view_rows;
