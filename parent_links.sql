-- =========================================================
-- Parent accounts & safe parent-child linking
-- Run this in the Supabase SQL Editor (safe to run more than once).
--
-- Flow:
--   1. The student opens "Parent Access" in the dashboard and gets
--      a Parent Link Code.
--   2. A parent creates a parent account and sends a link request
--      with that code.
--   3. The student approves the request. Only then can the parent
--      see the student's profile and projects. Either side can
--      remove the link at any time.
-- =========================================================

-- 1) Account roles -------------------------------------------------------
alter table public.profiles
    add column if not exists role text not null default 'student';

do $$
begin
    alter table public.profiles
        add constraint profiles_role_check
        check (role in ('student', 'teacher', 'parent'));
exception
    when duplicate_object then null;
end $$;

-- Repair parent accounts whose profile was created as "student" because the
-- role column was missing at sign-up time (e.g. after re-running the schema).
update public.profiles p
set role = 'parent'
from auth.users u
where u.id = p.id
  and u.raw_user_meta_data ->> 'role' = 'parent'
  and p.role <> 'parent';

-- Create the profile (with role) server-side at sign-up, so parent sign-ups
-- never depend on a client-side profiles write.
create or replace function public.handle_new_user()
returns trigger
language plpgsql
security definer
set search_path = public
as $$
declare
    meta_role text := coalesce(new.raw_user_meta_data ->> 'role', 'student');
begin
    if meta_role not in ('student', 'parent', 'teacher') then
        meta_role := 'student';
    end if;

    insert into public.profiles (id, fname, lname, bdate, age, sex, strand, grade, section, email, role)
    values (
        new.id,
        coalesce(nullif(new.raw_user_meta_data->>'fname', ''), 'Student'),
        coalesce(nullif(new.raw_user_meta_data->>'lname', ''), ''),
        nullif(new.raw_user_meta_data->>'bdate', '')::date,
        nullif(new.raw_user_meta_data->>'age', '')::int,
        nullif(new.raw_user_meta_data->>'sex', ''),
        coalesce(nullif(new.raw_user_meta_data->>'strand', ''), 'ICT'),
        nullif(new.raw_user_meta_data->>'grade', ''),
        nullif(new.raw_user_meta_data->>'section', ''),
        new.email,
        meta_role
    )
    on conflict (id) do nothing;
    return new;
end;
$$;

notify pgrst, 'reload schema';

-- 2) One Parent Link Code per student ------------------------------------
create table if not exists public.parent_link_codes (
    user_id    uuid primary key references auth.users(id) on delete cascade,
    code       text not null unique,
    created_at timestamptz not null default now()
);

-- 3) Parent <-> student links --------------------------------------------
create table if not exists public.parent_links (
    id           bigint generated by default as identity primary key,
    parent_id    uuid not null references auth.users(id) on delete cascade,
    student_id   uuid not null references auth.users(id) on delete cascade,
    status       text not null default 'pending'
                 check (status in ('pending', 'approved', 'declined')),
    message      text,
    created_at   timestamptz not null default now(),
    responded_at timestamptz,
    unique (parent_id, student_id),
    check (parent_id <> student_id)
);

create index if not exists parent_links_parent_idx
    on public.parent_links (parent_id, status);

create index if not exists parent_links_student_idx
    on public.parent_links (student_id, status);

-- 4) Student: get (or create) their Parent Link Code ---------------------
create or replace function public.ensure_parent_link_code()
returns text
language plpgsql
security definer
set search_path = public, pg_temp
as $$
declare
    v_uid  uuid := auth.uid();
    v_code text;
begin
    if v_uid is null then
        raise exception 'Please log in first.';
    end if;

    select code into v_code
    from public.parent_link_codes
    where user_id = v_uid;

    if v_code is not null then
        return v_code;
    end if;

    for i in 1..10 loop
        v_code := upper(substr(md5(random()::text), 1, 4) || '-' || substr(md5(random()::text), 1, 4));
        begin
            insert into public.parent_link_codes (user_id, code)
            values (v_uid, v_code);
            return v_code;
        exception
            when unique_violation then
                null;
        end;
    end loop;

    raise exception 'Could not create a Parent Link Code. Please try again.';
end;
$$;

-- 5) Parent: send a link request using the student's code ----------------
create or replace function public.request_parent_link(p_code text, p_message text default null)
returns public.parent_links
language plpgsql
security definer
set search_path = public, pg_temp
as $$
declare
    v_parent  uuid := auth.uid();
    v_student uuid;
    v_code    text := upper(regexp_replace(coalesce(p_code, ''), '[^A-Za-z0-9]', '', 'g'));
    v_row     public.parent_links;
begin
    if v_parent is null then
        raise exception 'Please log in first.';
    end if;

    if v_code = '' then
        raise exception 'Enter your child''s Parent Link Code.';
    end if;

    select user_id into v_student
    from public.parent_link_codes
    where regexp_replace(code, '[^A-Za-z0-9]', '', 'g') = v_code
    limit 1;

    if v_student is null then
        raise exception 'That Parent Link Code was not found. Check the code with your child.';
    end if;

    if v_student = v_parent then
        raise exception 'You cannot link your own account.';
    end if;

    if exists (
        select 1 from public.profiles
        where id = v_parent and role = 'student'
    ) then
        raise exception 'Only parent accounts can request a child link.';
    end if;

    select * into v_row
    from public.parent_links
    where parent_id = v_parent and student_id = v_student;

    if v_row.id is not null then
        if v_row.status = 'approved' then
            return v_row;
        end if;

        update public.parent_links
           set status = 'pending',
               message = nullif(trim(coalesce(p_message, '')), ''),
               created_at = now(),
               responded_at = null
         where id = v_row.id
         returning * into v_row;

        return v_row;
    end if;

    insert into public.parent_links (parent_id, student_id, message)
    values (v_parent, v_student, nullif(trim(coalesce(p_message, '')), ''))
    returning * into v_row;

    return v_row;
end;
$$;

-- 6) Student: approve or decline a request -------------------------------
create or replace function public.respond_parent_link(p_link_id bigint, p_approve boolean)
returns public.parent_links
language plpgsql
security definer
set search_path = public, pg_temp
as $$
declare
    v_row public.parent_links;
begin
    if auth.uid() is null then
        raise exception 'Please log in first.';
    end if;

    update public.parent_links
       set status = case when p_approve then 'approved' else 'declined' end,
           responded_at = now()
     where id = p_link_id
       and student_id = auth.uid()
     returning * into v_row;

    if v_row.id is null then
        raise exception 'Link request not found.';
    end if;

    return v_row;
end;
$$;

-- 7) Either side: remove a link ------------------------------------------
create or replace function public.revoke_parent_link(p_link_id bigint)
returns void
language plpgsql
security definer
set search_path = public, pg_temp
as $$
begin
    if auth.uid() is null then
        raise exception 'Please log in first.';
    end if;

    delete from public.parent_links
    where id = p_link_id
      and (parent_id = auth.uid() or student_id = auth.uid());
end;
$$;

-- 8) Parent: list linked children (all statuses) -------------------------
create or replace function public.my_children()
returns table (
    link_id      bigint,
    status       text,
    created_at   timestamptz,
    responded_at timestamptz,
    student_id   uuid,
    fname        text,
    lname        text,
    strand       text,
    grade        text,
    section      text,
    bio          text,
    avatar_url   text
)
language sql
security definer
set search_path = public, pg_temp
as $$
    select
        l.id,
        l.status,
        l.created_at,
        l.responded_at,
        l.student_id,
        p.fname,
        p.lname,
        p.strand,
        p.grade,
        p.section,
        p.bio,
        p.avatar_url
    from public.parent_links l
    left join public.profiles p on p.id = l.student_id
    where l.parent_id = auth.uid()
    order by l.created_at desc;
$$;

-- 9) Student: list parents who requested access --------------------------
create or replace function public.my_parent_links()
returns table (
    link_id      bigint,
    status       text,
    created_at   timestamptz,
    responded_at timestamptz,
    parent_id    uuid,
    fname        text,
    lname        text,
    email        text
)
language sql
security definer
set search_path = public, pg_temp
as $$
    select
        l.id,
        l.status,
        l.created_at,
        l.responded_at,
        l.parent_id,
        p.fname,
        p.lname,
        p.email
    from public.parent_links l
    left join public.profiles p on p.id = l.parent_id
    where l.student_id = auth.uid()
    order by l.created_at desc;
$$;

-- 10) Row Level Security ------------------------------------------------
alter table public.parent_link_codes enable row level security;
alter table public.parent_links enable row level security;

drop policy if exists "parent_link_codes_select_own" on public.parent_link_codes;
create policy "parent_link_codes_select_own"
    on public.parent_link_codes for select
    to authenticated
    using (user_id = auth.uid());

drop policy if exists "parent_links_select_parties" on public.parent_links;
create policy "parent_links_select_parties"
    on public.parent_links for select
    to authenticated
    using (parent_id = auth.uid() or student_id = auth.uid());

-- Writes go through the security-definer functions above only.

-- 11) Permissions -------------------------------------------------------
revoke execute on function public.ensure_parent_link_code() from public, anon;
revoke execute on function public.request_parent_link(text, text) from public, anon;
revoke execute on function public.respond_parent_link(bigint, boolean) from public, anon;
revoke execute on function public.revoke_parent_link(bigint) from public, anon;
revoke execute on function public.my_children() from public, anon;
revoke execute on function public.my_parent_links() from public, anon;

grant execute on function public.ensure_parent_link_code() to authenticated;
grant execute on function public.request_parent_link(text, text) to authenticated;
grant execute on function public.respond_parent_link(bigint, boolean) to authenticated;
grant execute on function public.revoke_parent_link(bigint) to authenticated;
grant execute on function public.my_children() to authenticated;
grant execute on function public.my_parent_links() to authenticated;

grant select on public.parent_link_codes to authenticated;
grant select on public.parent_links to authenticated;

-- 12) Quick check -------------------------------------------------------
select
    (select count(*) from public.parent_link_codes) as link_codes,
    (select count(*) from public.parent_links) as parent_links;
