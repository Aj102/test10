-- =========================================================
-- Skill-based discovery + faculty-curated exhibitions
-- Version: exhibitions v1
-- Run AFTER teacher_reviews.sql and privacy_sharing.sql.
-- Safe to run more than once.
--
-- Adds:
--   * community_directory(): grade / strand for students with public
--     showcase work (used by Community filters)
--   * exhibitions + exhibition_items tables
--   * Teacher-only curation RPCs (only public projects can be exhibited)
--   * Published exhibitions are readable by guests; writes only via RPCs
-- =========================================================

begin;

-- 1) Learner directory for grade / strand filters -------------------------
drop function if exists public.community_directory();

create or replace function public.community_directory()
returns table (
    id      uuid,
    fname   text,
    lname   text,
    grade   text,
    strand  text
)
language sql
security definer
stable
set search_path = public, pg_temp
as $$
    select pr.id,
           pr.fname,
           pr.lname,
           pr.grade,
           pr.strand
    from public.profiles pr
    where pr.role = 'student'
      and exists (
          select 1 from public.projects p
          where p.user_id = pr.id
            and p.is_public = true
      )
    order by pr.lname nulls last, pr.fname nulls last;
$$;

revoke all on function public.community_directory() from public, anon;
grant execute on function public.community_directory() to anon, authenticated;

-- 2) Exhibition storage ---------------------------------------------------
create table if not exists public.exhibitions (
    id           bigint generated by default as identity primary key,
    teacher_id   uuid not null references auth.users(id) on delete cascade,
    curator_name text,
    title        text not null,
    description  text,
    is_published boolean not null default true,
    created_at   timestamptz not null default now(),
    updated_at   timestamptz not null default now(),
    constraint exhibitions_title_check
        check (char_length(trim(title)) between 3 and 120),
    constraint exhibitions_description_check
        check (description is null or char_length(description) <= 2000)
);

create table if not exists public.exhibition_items (
    exhibition_id bigint not null references public.exhibitions(id) on delete cascade,
    project_id    bigint not null references public.projects(id) on delete cascade,
    position      integer not null default 0,
    added_at      timestamptz not null default now(),
    primary key (exhibition_id, project_id)
);

create index if not exists exhibitions_teacher_idx
    on public.exhibitions (teacher_id, created_at desc);

create index if not exists exhibitions_published_idx
    on public.exhibitions (is_published, created_at desc)
    where is_published = true;

create index if not exists exhibition_items_project_idx
    on public.exhibition_items (project_id);

create or replace function public.touch_exhibition()
returns trigger
language plpgsql
set search_path = ''
as $$
begin
    new.updated_at := now();
    return new;
end;
$$;

drop trigger if exists touch_exhibition on public.exhibitions;
create trigger touch_exhibition
    before update on public.exhibitions
    for each row execute function public.touch_exhibition();

-- 3) Only public showcase projects can be curated -------------------------
create or replace function public.validate_exhibition_item()
returns trigger
language plpgsql
security definer
set search_path = public, pg_temp
as $$
declare
    v_public boolean;
begin
    select is_public into v_public
    from public.projects
    where id = new.project_id;

    if v_public is null then
        raise exception 'Project not found.';
    end if;
    if not v_public then
        raise exception 'Only projects shared in the Community Showcase can be exhibited.';
    end if;

    return new;
end;
$$;

drop trigger if exists validate_exhibition_item on public.exhibition_items;
create trigger validate_exhibition_item
    before insert or update of project_id on public.exhibition_items
    for each row execute function public.validate_exhibition_item();

-- 4) Create / update an exhibition (teacher only) -------------------------
create or replace function public.save_exhibition(
    p_id           bigint,
    p_title        text,
    p_description  text,
    p_is_published boolean,
    p_project_ids  bigint[]
)
returns public.exhibitions
language plpgsql
security definer
set search_path = public, pg_temp
as $$
declare
    v_uid        uuid := auth.uid();
    v_role       text;
    v_name       text;
    v_title      text := trim(coalesce(p_title, ''));
    v_description text := nullif(trim(coalesce(p_description, '')), '');
    v_ids        bigint[];
    v_count      integer;
    v_public     integer;
    v_row        public.exhibitions;
begin
    if v_uid is null then
        raise exception 'Please log in first.';
    end if;

    select role, nullif(trim(coalesce(fname, '') || ' ' || coalesce(lname, '')), '')
      into v_role, v_name
    from public.profiles
    where id = v_uid;

    if v_role is distinct from 'teacher' then
        raise exception 'Only teacher accounts can curate exhibitions.';
    end if;

    if char_length(v_title) < 3 or char_length(v_title) > 120 then
        raise exception 'Give the exhibition a title between 3 and 120 characters.';
    end if;
    if v_description is not null and char_length(v_description) > 2000 then
        raise exception 'Description must be 2000 characters or fewer.';
    end if;

    select array_agg(x order by first_pos)
      into v_ids
    from (
        select x, min(ord) as first_pos
        from unnest(coalesce(p_project_ids, '{}'::bigint[])) with ordinality as u(x, ord)
        where x is not null
        group by x
    ) dedup;

    v_ids := coalesce(v_ids, '{}'::bigint[]);
    if cardinality(v_ids) = 0 then
        raise exception 'Choose at least one public project.';
    end if;

    select count(*) into v_count
    from public.projects
    where id = any (v_ids);

    select count(*) into v_public
    from public.projects
    where id = any (v_ids) and is_public = true;

    if v_count <> cardinality(v_ids) then
        raise exception 'One or more selected projects no longer exist.';
    end if;
    if v_public <> cardinality(v_ids) then
        raise exception 'Only projects shared in the Community Showcase can be exhibited.';
    end if;

    if p_id is null then
        insert into public.exhibitions
            (teacher_id, curator_name, title, description, is_published)
        values
            (v_uid, coalesce(v_name, 'Teacher'), v_title, v_description, coalesce(p_is_published, true))
        returning * into v_row;
    else
        update public.exhibitions
           set title = v_title,
               description = v_description,
               is_published = coalesce(p_is_published, true),
               curator_name = coalesce(v_name, 'Teacher')
         where id = p_id
           and teacher_id = v_uid
         returning * into v_row;

        if not found then
            raise exception 'Exhibition not found.';
        end if;

        delete from public.exhibition_items where exhibition_id = p_id;
    end if;

    insert into public.exhibition_items (exhibition_id, project_id, position)
    select v_row.id, u.id, (u.ord - 1)::integer
    from unnest(v_ids) with ordinality as u(id, ord);

    return v_row;
end;
$$;

-- 5) Delete an exhibition (owner only) ------------------------------------
create or replace function public.delete_exhibition(p_id bigint)
returns void
language plpgsql
security definer
set search_path = public, pg_temp
as $$
begin
    if auth.uid() is null then
        raise exception 'Please log in first.';
    end if;

    delete from public.exhibitions
    where id = p_id
      and teacher_id = auth.uid();

    if not found then
        raise exception 'Exhibition not found.';
    end if;
end;
$$;

-- 6) RLS: signed-in visitors read published exhibitions -------------------
alter table public.exhibitions enable row level security;
alter table public.exhibition_items enable row level security;

drop policy if exists "exhibitions_select_visible" on public.exhibitions;
create policy "exhibitions_select_visible"
    on public.exhibitions for select
    to authenticated
    using (is_published = true or teacher_id = auth.uid());

drop policy if exists "exhibition_items_select_visible" on public.exhibition_items;
create policy "exhibition_items_select_visible"
    on public.exhibition_items for select
    to authenticated
    using (
        exists (
            select 1 from public.exhibitions e
            where e.id = exhibition_id
              and (e.is_published = true or e.teacher_id = auth.uid())
        )
    );

-- Guests may browse published exhibitions from the public showcase.
drop policy if exists "exhibitions_select_public" on public.exhibitions;
create policy "exhibitions_select_public"
    on public.exhibitions for select
    to anon
    using (is_published = true);

drop policy if exists "exhibition_items_select_public" on public.exhibition_items;
create policy "exhibition_items_select_public"
    on public.exhibition_items for select
    to anon
    using (
        exists (
            select 1 from public.exhibitions e
            where e.id = exhibition_id
              and e.is_published = true
        )
    );

-- Writes stay closed: save_exhibition() and delete_exhibition() are the
-- only write paths.
revoke insert, update, delete on public.exhibitions from anon, authenticated;
revoke insert, update, delete on public.exhibition_items from anon, authenticated;
grant select on public.exhibitions to anon, authenticated;
grant select on public.exhibition_items to anon, authenticated;

revoke execute on function public.save_exhibition(bigint, text, text, boolean, bigint[])
    from public, anon;
grant execute on function public.save_exhibition(bigint, text, text, boolean, bigint[])
    to authenticated;

revoke execute on function public.delete_exhibition(bigint)
    from public, anon;
grant execute on function public.delete_exhibition(bigint)
    to authenticated;

notify pgrst, 'reload schema';

commit;

-- 7) Quick check ----------------------------------------------------------
select
    (select count(*) from information_schema.tables
      where table_schema = 'public'
        and table_name in ('exhibitions', 'exhibition_items')) as exhibition_tables,
    (select count(*) from pg_proc
      where pronamespace = 'public'::regnamespace
        and proname in ('community_directory', 'save_exhibition', 'delete_exhibition')) as exhibition_functions,
    (select count(*) from pg_trigger
      where tgrelid = 'public.exhibition_items'::regclass
        and tgname = 'validate_exhibition_item') as item_guard;
