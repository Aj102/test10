-- =========================================================
-- Teacher accounts: Feedback, Rubrics & Milestone Reviews
-- Run this in the Supabase SQL Editor (safe to run more than once).
--
-- Rules enforced here (and only here, so the client cannot bypass them):
--   * Only accounts whose profiles.role = 'teacher' can write reviews.
--   * Teachers can review projects that were posted to the Community
--     Showcase (is_public = true) and featured works (featured slots).
--   * Students can read the reviews about their own work; teachers can
--     read the reviews they wrote. Nobody can write directly to the
--     table - everything goes through submit_teacher_review().
-- =========================================================

-- 1) Teacher sign-ups must use a school email (same rule as students) ------
create or replace function public.enforce_student_email_domain()
returns trigger
language plpgsql
set search_path = ''
as $$
declare
  meta_role text := coalesce(new.raw_user_meta_data ->> 'role', 'student');
begin
  -- Ignore updates that do not touch the email (last_sign_in_at, metadata, confirmation, etc.)
  if tg_op = 'UPDATE' and new.email is not distinct from old.email then
    return new;
  end if;

  if meta_role in ('student', 'teacher')
     and (new.email is null or new.email !~* '^[a-z0-9._%+-]+@fatima\.edu\.ph$') then
    raise exception 'Student and teacher accounts must use an @fatima.edu.ph email address.'
      using errcode = '23514';
  end if;

  return new;
end;
$$;

-- 2) Review storage -------------------------------------------------------
create table if not exists public.teacher_reviews (
    id            bigint generated by default as identity primary key,
    teacher_id    uuid not null references auth.users(id) on delete cascade,
    student_id    uuid not null references auth.users(id) on delete cascade,
    project_id    bigint references public.projects(id) on delete cascade,
    featured_slot integer check (featured_slot between 1 and 4),
    kind          text not null check (kind in ('feedback', 'rubric', 'milestone')),
    message       text,
    scores        jsonb,
    total_score   integer,
    stage         text check (stage in ('proposal', 'draft', 'final')),
    status        text check (status in ('approved', 'needs_revision')),
    teacher_name  text,
    created_at    timestamptz not null default now(),
    updated_at    timestamptz not null default now(),
    constraint teacher_reviews_target_check
        check (project_id is not null or featured_slot is not null),
    constraint teacher_reviews_rubric_shape
        check (kind <> 'rubric' or (scores is not null and total_score is not null)),
    constraint teacher_reviews_milestone_shape
        check (kind <> 'milestone' or (stage is not null and status is not null))
);

create index if not exists teacher_reviews_student_idx
    on public.teacher_reviews (student_id, created_at desc);

create index if not exists teacher_reviews_project_idx
    on public.teacher_reviews (project_id)
    where project_id is not null;

create index if not exists teacher_reviews_featured_idx
    on public.teacher_reviews (student_id, featured_slot)
    where featured_slot is not null;

-- One rubric per teacher per target; one milestone review per stage.
create unique index if not exists teacher_reviews_one_rubric_idx
    on public.teacher_reviews (teacher_id, (coalesce(project_id, 0)), (coalesce(featured_slot, 0)))
    where kind = 'rubric';

create unique index if not exists teacher_reviews_one_milestone_idx
    on public.teacher_reviews (teacher_id, (coalesce(project_id, 0)), (coalesce(featured_slot, 0)), stage)
    where kind = 'milestone';

-- 3) Submit a review (the only write path) --------------------------------
create or replace function public.submit_teacher_review(
    p_kind           text,
    p_project_id     bigint default null,
    p_featured_owner uuid default null,
    p_featured_slot  integer default null,
    p_message        text default null,
    p_scores         jsonb default null,
    p_stage          text default null,
    p_status         text default null
)
returns public.teacher_reviews
language plpgsql
security definer
set search_path = public, pg_temp
as $$
declare
    v_teacher uuid := auth.uid();
    v_role    text;
    v_name    text;
    v_student uuid;
    v_public  boolean;
    v_slot    integer;
    v_message text := nullif(trim(coalesce(p_message, '')), '');
    v_scores  jsonb;
    v_total   integer := 0;
    v_key     text;
    v_val     numeric;
    v_keys    text[] := array['content', 'creativity', 'execution', 'organization', 'impact'];
    v_row     public.teacher_reviews;
    v_id      bigint;
begin
    if v_teacher is null then
        raise exception 'Please log in first.';
    end if;

    select role, nullif(trim(coalesce(fname, '') || ' ' || coalesce(lname, '')), '')
      into v_role, v_name
    from public.profiles
    where id = v_teacher;

    if v_role is distinct from 'teacher' then
        raise exception 'Only teacher accounts can submit reviews.';
    end if;

    if p_kind not in ('feedback', 'rubric', 'milestone') then
        raise exception 'Unknown review type.';
    end if;

    -- Resolve the student owner from the chosen target.
    if p_project_id is not null then
        select user_id, is_public into v_student, v_public
        from public.projects
        where id = p_project_id;

        if v_student is null then
            raise exception 'Project not found.';
        end if;
        if not coalesce(v_public, false) then
            raise exception 'Only projects posted to the Community Showcase can receive teacher reviews.';
        end if;
        v_slot := null;

    elsif p_featured_owner is not null and p_featured_slot is not null then
        select user_id into v_student
        from public.featured
        where user_id = p_featured_owner and slot = p_featured_slot;

        if v_student is null then
            raise exception 'That featured work was not found.';
        end if;
        v_slot := p_featured_slot;

    else
        raise exception 'Choose a posted project or a featured work to review.';
    end if;

    if p_kind = 'feedback' then
        if v_message is null then
            raise exception 'Write your feedback before posting.';
        end if;
        if length(v_message) > 2000 then
            raise exception 'Feedback must be 2000 characters or fewer.';
        end if;

        insert into public.teacher_reviews
            (teacher_id, student_id, project_id, featured_slot, kind, message, teacher_name)
        values
            (v_teacher, v_student, p_project_id, v_slot, 'feedback', v_message, coalesce(v_name, 'Teacher'))
        returning * into v_row;

        return v_row;
    end if;

    if p_kind = 'rubric' then
        if p_scores is null or jsonb_typeof(p_scores) <> 'object' then
            raise exception 'Score every rubric criterion before saving.';
        end if;

        for v_key in select jsonb_object_keys(p_scores) loop
            if not (v_key = any (v_keys)) then
                raise exception 'Unknown rubric criterion: %', v_key;
            end if;
        end loop;

        foreach v_key in array v_keys loop
            v_val := nullif(p_scores ->> v_key, '')::numeric;
            if v_val is null or v_val < 1 or v_val > 5 then
                raise exception 'Rubric scores must be between 1 and 5.';
            end if;
            v_total := v_total + v_val;
        end loop;

        v_scores := p_scores;

        select id into v_id
        from public.teacher_reviews
        where kind = 'rubric'
          and teacher_id = v_teacher
          and project_id is not distinct from p_project_id
          and featured_slot is not distinct from v_slot;

        if v_id is null then
            insert into public.teacher_reviews
                (teacher_id, student_id, project_id, featured_slot, kind,
                 message, scores, total_score, teacher_name)
            values
                (v_teacher, v_student, p_project_id, v_slot, 'rubric',
                 v_message, v_scores, v_total, coalesce(v_name, 'Teacher'))
            returning * into v_row;
        else
            update public.teacher_reviews
               set message = v_message,
                   scores = v_scores,
                   total_score = v_total,
                   teacher_name = coalesce(v_name, 'Teacher'),
                   updated_at = now()
             where id = v_id
             returning * into v_row;
        end if;

        return v_row;
    end if;

    -- Milestone review
    if p_stage not in ('proposal', 'draft', 'final') then
        raise exception 'Choose the milestone stage.';
    end if;
    if p_status not in ('approved', 'needs_revision') then
        raise exception 'Choose a milestone status.';
    end if;

    select id into v_id
    from public.teacher_reviews
    where kind = 'milestone'
      and teacher_id = v_teacher
      and stage = p_stage
      and project_id is not distinct from p_project_id
      and featured_slot is not distinct from v_slot;

    if v_id is null then
        insert into public.teacher_reviews
            (teacher_id, student_id, project_id, featured_slot, kind,
             message, stage, status, teacher_name)
        values
            (v_teacher, v_student, p_project_id, v_slot, 'milestone',
             v_message, p_stage, p_status, coalesce(v_name, 'Teacher'))
        returning * into v_row;
    else
        update public.teacher_reviews
           set message = v_message,
               status = p_status,
               teacher_name = coalesce(v_name, 'Teacher'),
               updated_at = now()
         where id = v_id
         returning * into v_row;
    end if;

    return v_row;
end;
$$;

-- 4) Row Level Security ---------------------------------------------------
alter table public.teacher_reviews enable row level security;

drop policy if exists "teacher_reviews_select_involved" on public.teacher_reviews;
create policy "teacher_reviews_select_involved"
    on public.teacher_reviews for select
    to authenticated
    using (teacher_id = auth.uid() or student_id = auth.uid());

-- Direct writes stay closed: the security-definer function above is the
-- only way in or out.
revoke insert, update, delete on public.teacher_reviews from anon, authenticated;
grant select on public.teacher_reviews to authenticated;

-- 5) Permissions ----------------------------------------------------------
revoke execute on function public.submit_teacher_review(text, bigint, uuid, integer, text, jsonb, text, text)
    from public, anon;
grant execute on function public.submit_teacher_review(text, bigint, uuid, integer, text, jsonb, text, text)
    to authenticated;

notify pgrst, 'reload schema';

-- 6) Quick check ----------------------------------------------------------
select
    (select count(*) from public.teacher_reviews) as review_rows,
    (select count(*) from pg_trigger
      where tgrelid = 'auth.users'::regclass
        and tgname = 'enforce_student_email_domain') as email_domain_trigger;
